const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

/**
 * 检测和配置FFmpeg
 * @returns {Object} FFmpeg配置信息
 */
function configureFFmpeg() {
    let ffmpegPath = null;
    let isAvailable = false;
    
    try {
        // 尝试直接执行ffmpeg命令
        execSync('ffmpeg -version', { stdio: 'ignore' });
        ffmpegPath = 'ffmpeg';
        isAvailable = true;
    } catch (error) {
        // FFmpeg未在系统路径中，尝试寻找本地FFmpeg
        const possiblePaths = [
            // 项目根目录下的ffmpeg目录
            path.join(__dirname, '..', '..', 'ffmpeg'),
            // 系统常见的FFmpeg安装目录
            'C:\\ffmpeg',
            'C:\\Program Files\\ffmpeg',
            // 自定义安装路径
            'D:\\Trae CN\\ffmpeg-master-latest-win64-gpl-shared'
        ];
        
        for (const basePath of possiblePaths) {
            const ffmpegExePath = path.join(basePath, 'bin', 'ffmpeg.exe');
            if (fs.existsSync(ffmpegExePath)) {
                // 验证FFmpeg可执行文件是否真的可用
                try {
                    execSync(`"${ffmpegExePath}" -version`, { stdio: 'ignore' });
                    ffmpegPath = ffmpegExePath;
                    isAvailable = true;
                    break;
                } catch (e) {
                    // 虽然文件存在，但不可执行，继续寻找
                    console.warn(`FFmpeg file exists but is not executable: ${ffmpegExePath}`);
                }
            }
        }
    }
    
    console.log('FFmpeg configuration:', { isAvailable, path: ffmpegPath });
    return {
        isAvailable,
        path: ffmpegPath
    };
}

/**
 * 生成视频文件
 * @param {string} outputPath - 输出文件路径
 * @param {Object} params - 视频参数
 * @returns {boolean} 是否成功生成视频
 */
function generateVideo(outputPath, params = {}) {
    const ffmpegConfig = configureFFmpeg();
    
    if (!ffmpegConfig.isAvailable) {
        console.warn('FFmpeg not available, falling back to simple MP4 generation');
        return createSimpleMP4(outputPath);
    }
    
    try {
        const { videoTitle = 'Generated Video', videoStyle = 'realistic', videoModel = 'veo', videoDescription = '' } = params;
        
        // 视频模型到时长的映射表
        const videoModelToDuration = {
            'animatediff': 15,      // AnimateDiff SD (15s - Free)
            'animatediff-stable': 10, // AnimateDiff Stable (10s - Free)
            'pika': 12,             // Pika AI (12s - Free)
            'stableVideo': 20,       // Stable Video Diffusion (20s - Free)
            'veo': 10,              // Default fallback
            'default': 10            // Default duration
        };
        
        // 获取视频时长
        const duration = videoModelToDuration[videoModel] || videoModelToDuration['default'];
        
        // 根据视频风格选择背景颜色
        let bgColor = 'blue';
        if (videoStyle.includes('cartoon')) bgColor = 'yellow';
        if (videoStyle.includes('anime')) bgColor = 'pink';
        if (videoStyle.includes('3d')) bgColor = 'green';
        if (videoStyle.includes('documentary')) bgColor = 'gray';
        
        // 构建FFmpeg命令，添加更多视觉元素，使视频内容更加丰富
        const command = `"${ffmpegConfig.path}" -f lavfi -i color=c=${bgColor}:s=1280x720:r=25 -f lavfi -i anullsrc=r=44100:cl=stereo -t ${duration} -vf "drawtext=text='${videoTitle}':fontcolor=white:fontsize=36:box=1:boxcolor=black@0.5:boxborderw=5:x=(w-text_w)/2:y=(h-text_h)/2,drawtext=text='${videoDescription || 'Generated Video'}':fontcolor=white:fontsize=24:box=1:boxcolor=black@0.5:boxborderw=3:x=(w-text_w)/2:y=(h-text_h)/2+60" -c:v libx264 -preset medium -crf 23 -pix_fmt yuv420p -c:a aac -b:a 128k -movflags faststart "${outputPath}"`;
        
        console.log('Generating video with model:', videoModel, 'duration:', duration, 'seconds');
        
        // 执行FFmpeg命令
        execSync(command, { stdio: 'ignore' });
        return true;
    } catch (error) {
        console.error('Error generating video with FFmpeg:', error.message);
        //  fallback到简单MP4生成
        return createSimpleMP4(outputPath);
    }
}

